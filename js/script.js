let cart=JSON.parse(localStorage.getItem("bookhaven_cart")||"[]");
let currentUser=JSON.parse(localStorage.getItem("bookhaven_user")||"null");
let reviews=JSON.parse(localStorage.getItem("bookhaven_reviews")||"{}");
const money=n=>new Intl.NumberFormat("vi-VN").format(n)+"₫";
const $=id=>document.getElementById(id);
const stars=r=>{let n=Math.round(r);return "★".repeat(n)+"☆".repeat(5-n)};
function save(){localStorage.setItem("bookhaven_cart",JSON.stringify(cart));localStorage.setItem("bookhaven_user",JSON.stringify(currentUser));localStorage.setItem("bookhaven_reviews",JSON.stringify(reviews));}
function renderCategories(){let cats=[...new Set(books.flatMap(b=>b.genre.split(",").map(x=>x.trim())))];$("categoryFilter").innerHTML='<option value="">Tất cả thể loại</option>'+cats.map(c=>`<option value="${c}">${c}</option>`).join("");$("categoryPills").innerHTML=cats.map(c=>`<button class="pill" onclick="filterCategory('${c.replaceAll("'","\\'")}')">${c}</button>`).join("");}
function filterCategory(c){$("categoryFilter").value=c;document.querySelector("#books").scrollIntoView({behavior:"smooth"});renderBooks();}
function renderBooks(){let q=$("searchInput").value.toLowerCase().trim(),cat=$("categoryFilter").value,sort=$("sortSelect").value;let list=books.filter(b=>(!q||`${b.title} ${b.author} ${b.genre}`.toLowerCase().includes(q))&&(!cat||b.genre.includes(cat)));if(sort==="priceAsc")list.sort((a,b)=>a.price-b.price);if(sort==="priceDesc")list.sort((a,b)=>b.price-a.price);if(sort==="name")list.sort((a,b)=>a.title.localeCompare(b.title));if(sort==="rating")list.sort((a,b)=>b.rating-a.rating);$("bookGrid").innerHTML=list.length?list.map(b=>`<article class="book-card"><div class="cover"><img src="${b.image}" alt="${b.title}"></div><div class="book-body"><h3 class="book-title">${b.title}</h3><div class="author">${b.author}</div><span class="tag">${b.genre.split(",")[0]}</span><div class="book-footer"><span class="price">${money(b.price)}</span><button class="detail-link" onclick="openDetail(${b.id})">Xem chi tiết →</button></div></div></article>`).join(""):'<p class="muted">Không tìm thấy sách phù hợp.</p>';}
function showHome(){$("homePage").classList.remove("hidden");$("detailPage").classList.add("hidden");window.scrollTo({top:0,behavior:"smooth"});}
let selectedRating=0;
function openDetail(id){let b=books.find(x=>x.id===id);if(!b)return;let extra=reviews[b.id]||[],all=[...b.reviews,...extra],avg=all.length?all.reduce((s,r)=>s+r.rating,0)/all.length:b.rating;$("homePage").classList.add("hidden");$("detailPage").classList.remove("hidden");$("detailPage").innerHTML=`<div class="container detail"><button class="back" onclick="showHome()">← Quay lại danh sách sách</button><div class="detail-top"><div class="detail-cover"><img src="${b.image}" alt="${b.title}"></div><div><p class="eyebrow">${b.genre}</p><h1>${b.title}</h1><p class="muted">Tác giả: <b>${b.author}</b></p><div class="detail-meta"><span class="stars">${stars(avg)}</span><span class="rating-number">${avg.toFixed(1)}/5</span><span class="muted">(${all.length} đánh giá)</span></div><p class="detail-summary">${b.summary}</p><div class="detail-price">${money(b.price)}</div><button class="primary-btn" onclick="addToCart(${b.id})">🛒 Thêm vào giỏ hàng</button></div></div><section class="detail-section"><p class="eyebrow">NỘI DUNG</p><h2>Tóm tắt & mô tả</h2><p class="detail-summary">${b.summary}</p></section><section class="detail-section"><p class="eyebrow">ĐỘC GIẢ NÓI GÌ?</p><h2>Đánh giá của độc giả</h2><div class="review-grid"><div class="rating-box"><div class="rating-big">${avg.toFixed(1)}</div><div class="stars">${stars(avg)}</div><p class="muted">${all.length} đánh giá</p></div><div>${all.map(r=>`<div class="review"><div class="review-head"><span class="review-name">${r.name}</span><span class="stars">${stars(r.rating)}</span></div><p>${r.comment}</p></div>`).join("")}</div></div><div class="review-form"><b>Viết đánh giá của bạn</b><p class="muted">Bạn cần đăng nhập để gửi đánh giá.</p><div class="star-select" id="starSelect">${[1,2,3,4,5].map(n=>`<span data-star="${n}" onclick="selectRating(${n})">☆</span>`).join("")}</div><textarea id="reviewText" placeholder="Chia sẻ cảm nhận của bạn..."></textarea><button class="primary-btn" onclick="submitReview(${b.id})">Gửi đánh giá</button></div></section></div>`;window.scrollTo({top:0,behavior:"smooth"});}
function selectRating(n){selectedRating=n;document.querySelectorAll("#starSelect span").forEach(s=>{let on=Number(s.dataset.star)<=n;s.classList.toggle("active",on);s.textContent=on?"★":"☆";});}
function submitReview(id){if(!currentUser){openAuth();toast("Vui lòng đăng nhập trước khi đánh giá.");return}let text=$("reviewText").value.trim();if(!selectedRating||!text){toast("Hãy chọn số sao và nhập nội dung đánh giá.");return}if(!reviews[id])reviews[id]=[];reviews[id].push({name:currentUser.name,rating:selectedRating,comment:text});save();selectedRating=0;openDetail(id);toast("Đã gửi đánh giá.");}
function addToCart(id){let item=cart.find(x=>x.id===id);if(item)item.qty++;else cart.push({id,qty:1});save();updateCartCount();toast("Đã thêm sách vào giỏ hàng.");}
function updateCartCount(){$("cartCount").textContent=cart.reduce((s,x)=>s+x.qty,0);}
function openCart(){$("cartItems").innerHTML=cart.map(item=>{let b=books.find(x=>x.id===item.id);return `<div class="cart-row"><img src="${b.image}" alt=""><div><div class="cart-name">${b.title}</div><div class="muted">${money(b.price)}</div><div class="qty"><button onclick="changeQty(${b.id},-1)">−</button><span>${item.qty}</span><button onclick="changeQty(${b.id},1)">+</button></div></div><strong>${money(b.price*item.qty)}</strong></div>`}).join("")||'<p class="muted">Giỏ hàng đang trống.</p>';$("cartTotal").textContent=money(cart.reduce((s,x)=>{let b=books.find(y=>y.id===x.id);return s+b.price*x.qty},0));$("cartModal").classList.remove("hidden");}
function closeCart(){$("cartModal").classList.add("hidden")}
function changeQty(id,d){let item=cart.find(x=>x.id===id);if(!item)return;item.qty+=d;if(item.qty<=0)cart=cart.filter(x=>x.id!==id);save();updateCartCount();openCart();}
function checkout(){if(!cart.length){toast("Giỏ hàng đang trống.");return}if(!currentUser){closeCart();openAuth();toast("Đăng nhập để tiếp tục thanh toán.");return}toast("Đặt hàng thành công (chế độ mô phỏng).");cart=[];save();updateCartCount();closeCart();}
function openAuth(){$("loginError").textContent="";$("authModal").classList.remove("hidden")}function closeAuth(){$("authModal").classList.add("hidden")}
function login(e){e.preventDefault();let email=$("loginEmail").value.trim().toLowerCase(),pass=$("loginPassword").value;if(email==="demo@bookhaven.vn"&&pass==="123456"){currentUser={name:"Độc giả BookHaven",email};save();closeAuth();updateUser();toast("Đăng nhập thành công.");}else $("loginError").textContent="Email hoặc mật khẩu không đúng. Hãy dùng tài khoản demo ở bên dưới.";}
function logout(){currentUser=null;save();updateUser();toast("Đã đăng xuất.");}function updateUser(){$("userBtn").textContent=currentUser?currentUser.name+" · Đăng xuất":"Đăng nhập";$("userBtn").onclick=currentUser?logout:openAuth;}
function toast(msg){let t=$("toast");t.textContent=msg;t.classList.add("show");setTimeout(()=>t.classList.remove("show"),2200);}
